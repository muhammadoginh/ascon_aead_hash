#!/usr/bin/env python3
"""Generate ascon_aead_hash.srcs/sim_1/new/tb_vectors.svh for the unified-core testbenches.

Uses the NIST SP 800-232 compliant model in this folder (ascon.py).  Every
multi-byte value is emitted as the little-endian integer of its byte string,
which is the RTL convention (byte 0 of a block in bits [7:0], S0 = bytes 0..7).
"""
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import ascon  # noqa: E402

OUT = os.path.normpath(os.path.join(HERE, "..", "ascon_aead_hash.srcs", "sim_1", "new", "tb_vectors.svh"))
N_VECTORS = 64


def le(data: bytes, nbytes: int) -> int:
    assert len(data) <= nbytes
    return int.from_bytes(data.ljust(nbytes, b"\x00"), "little")


def sv(value: int, bits: int) -> str:
    return f"{bits}'h{value:0{bits // 4}x}"


def rnd(n: int) -> bytes:
    return bytes(random.getrandbits(8) for _ in range(n))


def main() -> None:
    random.seed(20261022)
    # vector 0 is a full 64-byte stream in both sets (used for cycle measurement)
    hash_lens = [64, 0, 1, 7, 8, 9, 15, 16, 17, 23, 24, 25, 31, 32, 33, 39, 40, 41,
                 47, 48, 49, 55, 56, 57, 63]
    hash_lens += [random.randint(0, 64) for _ in range(N_VECTORS - len(hash_lens))]
    aead_lens = [(0, 64), (0, 0), (0, 1), (0, 15), (0, 16), (0, 17), (0, 31), (0, 32), (0, 33),
                 (0, 63), (1, 0), (15, 0), (16, 0), (17, 0), (31, 0), (32, 0), (33, 0), (64, 0),
                 (16, 16), (32, 32), (31, 33), (33, 47), (64, 64), (5, 5), (48, 1), (1, 48),
                 (63, 64), (64, 63)]
    aead_lens += [(random.randint(0, 64), random.randint(0, 64))
                  for _ in range(N_VECTORS - len(aead_lens))]

    out = []
    w = out.append
    w("// Generated by python_simulation/gen_tb_vectors.py -- DO NOT EDIT")
    w("// All values are little-endian integers of the byte strings (SP 800-232 convention).")
    w(f"localparam int N_HASH = {len(hash_lens)};")
    w(f"localparam int N_AEAD = {len(aead_lens)};")
    kat_hash = ascon.ascon_hash(b"aaaaa")
    kat_enc = ascon.ascon_encrypt(bytes(16), bytes(16), b"", b"aaaa")
    w(f"localparam logic [255:0] KAT_HASH_AAAAA  = {sv(le(kat_hash, 32), 256)};  // Hash256(\"aaaaa\")")
    w(f"localparam logic [31:0]  KAT_ENC_AAAA_CT  = {sv(le(kat_enc[:4], 4), 32)};  // AEAD128(K=0, N=0, AD=\"\", PT=\"aaaa\")")
    w(f"localparam logic [127:0] KAT_ENC_AAAA_TAG = {sv(le(kat_enc[4:], 16), 128)};")
    w("int           hash_len   [0:N_HASH-1];")
    w("logic [511:0] hash_msg   [0:N_HASH-1];")
    w("logic [255:0] hash_md    [0:N_HASH-1];")
    w("logic [127:0] aead_key   [0:N_AEAD-1];")
    w("logic [127:0] aead_nonce [0:N_AEAD-1];")
    w("int           aead_adlen [0:N_AEAD-1];")
    w("int           aead_ptlen [0:N_AEAD-1];")
    w("logic [511:0] aead_ad    [0:N_AEAD-1];")
    w("logic [511:0] aead_pt    [0:N_AEAD-1];")
    w("logic [511:0] aead_ct    [0:N_AEAD-1];")
    w("logic [127:0] aead_tag   [0:N_AEAD-1];")
    w("task automatic load_vectors();")
    for i, length in enumerate(hash_lens):
        msg = rnd(length)
        md = ascon.ascon_hash(msg)
        w(f"  hash_len[{i}] = {length}; hash_msg[{i}] = {sv(le(msg, 64), 512)}; "
          f"hash_md[{i}] = {sv(le(md, 32), 256)};")
    for i, (adlen, ptlen) in enumerate(aead_lens):
        key, nonce, ad, pt = rnd(16), rnd(16), rnd(adlen), rnd(ptlen)
        ct_tag = ascon.ascon_encrypt(key, nonce, ad, pt)
        assert ascon.ascon_decrypt(key, nonce, ad, ct_tag) == pt
        ct, tag = ct_tag[:ptlen], ct_tag[ptlen:]
        w(f"  aead_key[{i}] = {sv(le(key, 16), 128)}; aead_nonce[{i}] = {sv(le(nonce, 16), 128)};")
        w(f"  aead_adlen[{i}] = {adlen}; aead_ad[{i}] = {sv(le(ad, 64), 512)};")
        w(f"  aead_ptlen[{i}] = {ptlen}; aead_pt[{i}] = {sv(le(pt, 64), 512)}; "
          f"aead_ct[{i}] = {sv(le(ct, 64), 512)}; aead_tag[{i}] = {sv(le(tag, 16), 128)};")
    w("endtask")
    with open(OUT, "w", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"wrote {OUT}: {len(hash_lens)} hash + {len(aead_lens)} AEAD vectors")


if __name__ == "__main__":
    main()
